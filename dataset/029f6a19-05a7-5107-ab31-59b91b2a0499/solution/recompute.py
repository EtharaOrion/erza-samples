#!/usr/bin/env python3
"""Regenerate the ground truth and reconcile it against the shipped fixtures.

GENERATED by .omo/verifier-kit/emit_grounding.py. Source of truth: grounding.yaml.

    python3 solution/recompute.py [--check]

`FORGE.md:89` requires one script to derive the golden trajectory, the checker fixtures, the
executable oracle and the generated ground truth from one source so they cannot disagree. This
script owns two of those and checks the third:

  * it regenerates solution/TRUTH.md from grounding.yaml, byte-for-byte
  * it reconciles every golden and tolerance in grounding.yaml against the ones the shipped
    verifier asserts in tests/expected_values.json

`--check` writes nothing and exits non-zero on any drift, which is the mode CRUCIBLE.md:72
G-TRUTH-REGEN re-runs.
"""
import argparse, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

HERE = os.path.dirname(os.path.abspath(__file__))
BUNDLE = os.path.dirname(HERE)


def load_grounding():
    import yaml
    with open(os.path.join(HERE, "grounding.yaml"), encoding="utf-8") as fh:
        g = yaml.safe_load(fh)
    nar = g.get("narrative_source")
    if nar:
        p = os.path.join(BUNDLE, nar)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                g["_narrative_text"] = fh.read()
    return g


def render_truth(g):
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "emit_grounding", os.path.join(BUNDLE, "solution", "_truth_template.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.render(g)


def reconcile(g):
    """Every golden the truth states must equal the golden the verifier asserts."""
    p = os.path.join(BUNDLE, "tests", "expected_values.json")
    if not os.path.isfile(p):
        return ["tests/expected_values.json absent; nothing to reconcile against"]
    with open(p, encoding="utf-8") as fh:
        spec = json.load(fh)
    shipped = {}
    for c in (spec.get("cases") or []):
        key = (c.get("case_id"), c.get("output") or c.get("output_key"))
        shipped[key] = c.get("golden")
    if not shipped:
        # bespoke flat schema: the graded value lives at ref_<name>
        for k, v in spec.items():
            if isinstance(v, (dict, list, bool)) or not isinstance(v, (int, float)):
                continue
            for pre in ("ref_", "reference_"):
                if k.startswith(pre):
                    name = k[len(pre):]
                    shipped[(name, name)] = v
                    break
    if not shipped:
        src_map = next((spec[k] for k in ("goldens", "golden")
                        if isinstance(spec.get(k), dict)), spec)
        for station, fields in src_map.items():
            if not isinstance(fields, dict):
                continue
            for field, val in fields.items():
                if not isinstance(val, (dict, list)):
                    shipped[(f"{station}:{field}", field)] = val
    bad = []
    for c in (g.get("graded_cases") or []):
        key = (c.get("case_id"), c.get("output"))
        if key not in shipped:
            bad.append(f"grounding case {key} is not graded by the shipped verifier")
        elif shipped[key] != c.get("golden"):
            bad.append(f"golden disagrees for {key}: grounding={c.get('golden')} "
                       f"verifier={shipped[key]}")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    g = load_grounding()
    truth = render_truth(g)
    tp = os.path.join(HERE, "TRUTH.md")
    drift = []
    if os.path.isfile(tp):
        with open(tp, encoding="utf-8") as fh:
            if fh.read() != truth:
                drift.append("solution/TRUTH.md differs from what grounding.yaml regenerates")
    elif a.check:
        drift.append("solution/TRUTH.md absent")
    drift += reconcile(g)
    if a.check:
        for d in drift:
            print(f"DRIFT: {d}")
        print("OK: truth regenerates and reconciles" if not drift else f"{len(drift)} drift(s)")
        return 1 if drift else 0
    with open(tp, "w", encoding="utf-8") as fh:
        fh.write(truth)
    print(f"wrote {os.path.relpath(tp, BUNDLE)} ({len(truth)} bytes)")
    for d in reconcile(g):
        print(f"RECONCILE: {d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
