"""Deterministic TRUTH.md renderer. GENERATED; source of truth is grounding.yaml.

Kept beside recompute.py so the rendering is one function with no hidden state: the same
grounding.yaml always produces the same bytes, which is what makes the regeneration check in
CRUCIBLE.md:72 (G-TRUTH-REGEN) meaningful.
"""

BANNER = "GENERATED SECTION. DO NOT HAND-EDIT."


def render(g):
    L = []
    a = L.append
    a(f"<!-- {BANNER} -->")
    a(f"<!-- Source of truth: grounding.yaml. Regenerate with: python3 solution/recompute.py -->")
    a("")
    a(f"# Ground truth - {g.get('task_id')}")
    a("")
    a(f"_{BANNER} Generated by `solution/recompute.py` from `grounding.yaml`._")
    a("")
    a("## The route that satisfies instruction.md")
    a("")
    a(f"The executable derivation is `{g.get('oracle_entry')}`, which the harness runs through the")
    a("Harbor oracle path and which must reach full reward. This document is the human-readable")
    a("projection of that derivation: it states what the graded outcome is, which checker asserts")
    a("it, and which competing routes the checkers reject.")
    a("")
    a(f"- Output contract: `{g.get('output_path')}` ({g.get('output_format')})")
    a(f"- Graded outcomes: {len(g.get('graded_cases') or [])}")
    a(f"- Checker entry point: `{g.get('checker_entry')}`")
    if g.get("method_note"):
        a("")
        a(f"Method as recorded by the authoring key: {g['method_note']}")
    a("")
    a("## Graded outcomes, and the checker each one satisfies")
    a("")
    a("Every case below is asserted by the checker at the entry point above, against the tolerance")
    a("shown. A submission satisfies this task when every case lands inside its tolerance.")
    a("")
    a("The golden VALUES are deliberately not tabled here. The authored trajectory embedded below")
    a("is written so that no step states what it evaluates to, which is what lets it double as a")
    a("grader artifact a judge panel can read. Tabling the answers beside it would destroy that")
    a("property. The goldens live in grounding.yaml, and `recompute.py --check` is what reconciles")
    a("them against the shipped verifier - a machine check, not a number printed next to the prose.")
    a("")
    a("| case | output | tolerance | unit |")
    a("|---|---|---|---|")
    for c in (g.get("graded_cases") or []):
        a(f"| `{c.get('case_id')}` | `{c.get('output')}` | "
          f"{c.get('tolerance_abs')} | {str(c.get('unit') or '').replace('|', '/')} |")
    a("")
    gaps = g.get("rejected_routes") or []
    a("## Plausible routes the checkers reject, and why each rejection is correct")
    a("")
    if not gaps:
        a("The authoring key records no control-gap ledger for this bundle, so the rejected-route")
        a("set is a named coverage gap rather than an empty result.")
    else:
        a("Each route below is a real competing method, not a strawman. The recorded gap is how far")
        a("outside tolerance that route lands, which is what makes the rejection correct rather")
        a("than a matter of preference.")
        a("")
        for name, detail in gaps:
            a(f"### `{name}`")
            a("")
            a(str(detail).strip())
            a("")
    nar = g.get("narrative_source")
    if nar and g.get("_narrative_text"):
        a("## The authored golden trajectory")
        a("")
        a(f"Carried byte-for-byte from `{nar}`, the ordered step-by-step derivation an author")
        a("wrote for this task. Reproduced rather than summarised, because FORGE.md:94 asks")
        a("TRUTH.md for the route itself and a paraphrase of a derivation is not a derivation.")
        a("")
        a("<!-- BEGIN AUTHORED NARRATIVE -->")
        a(g["_narrative_text"].rstrip())
        a("<!-- END AUTHORED NARRATIVE -->")
        a("")
    else:
        a("## Authored golden trajectory: ABSENT")
        a("")
        a("This bundle carries no authored step-by-step trajectory, so this file states the")
        a("graded surface and the rejected routes only and the oracle is the derivation. That is")
        a("a named coverage gap, not a complete ground truth.")
        a("")
    return "\n".join(L)
